"""Shared paths, the corpus-asset map, and the generated-template fixture.

The suites under `scripts/` are the real tests: each one produces an artifact a
human can open, prints a report worth reading, and exits non-zero on failure.
This package does not replace them -- it runs them, so a regression shows up in
one command instead of in whoever's terminal happened to run the right script.
"""

import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = REPO_ROOT / "scripts"

# The suite wrappers run scripts as subprocesses, so they never needed `app`
# importable here. Tests that check a contract in-process do.
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

# Every script computes this same path for itself (see
# `scripts/test_region_detection.py`): the corpus lives outside the repo
# because the sample documents are YMSLI's, not ours to commit.
FILES_DIR = REPO_ROOT.parent / "Files"

GENERATED_TEMPLATE = FILES_DIR / "Workshop Readout Template.pptx"
TEMPLATE_BUILDER = SCRIPTS_DIR / "build_workshop_readout_template.py"
MOM = "MOM Sample.xlsx"
BFL = "BFL Sample.xlsx"
POC = "POC List sample.xlsx"
BRD = "BRD Sample.docx"
CORPORATE_DECK = "YMSLI_Hackathon_2026_Introduction_Session 2(1).pptx"

# Which corpus files each suite needs to be meaningful. Stated explicitly rather
# than inferred from a script's error text: a missing input is a *skip* with the
# path named, never a failure. A red run caused by an asset nobody copied to
# this machine is how a suite stops being trusted -- which is exactly what
# `test_pptx_pipeline` looks like today on a checkout without the corporate deck.
#
# A script absent from this map has no declared requirement and simply runs, so
# a new suite needs no edit here to be picked up.
REQUIRED_ASSETS: dict[str, list[str]] = {
    "test_surgical_compile": [MOM],
    "test_region_detection": [MOM, BFL, POC],
    "test_compiler_ops": [MOM, BFL],
    "test_docx_region_detection": [BRD],
    "test_docx_compile": [BRD],
    # The deck is a real corporate asset; the template beside it is generated by
    # the fixture below.
    "test_pptx_pipeline": [CORPORATE_DECK],
    "test_ingestion_pipeline": [MOM, BFL, POC, BRD],
    # The deck here is the generated template, built by the fixture below.
    "test_conversation": [MOM, BRD],
}

SUITE_TIMEOUT_SECONDS = 300


def missing_assets(script_name: str) -> list[Path]:
    return [
        FILES_DIR / name
        for name in REQUIRED_ASSETS.get(script_name, [])
        if not (FILES_DIR / name).exists()
    ]


def run_script(path: Path, timeout: int = SUITE_TIMEOUT_SECONDS) -> subprocess.CompletedProcess:
    """Run one suite in its own interpreter process.

    A subprocess rather than an import, for two reasons: each script does its
    own `sys.path.insert` and expects to own the process, and running them
    separately keeps one suite's artifacts and module state out of the next
    one's way. `sys.executable` rather than a hardcoded `uv run` -- not every
    machine on this team has uv, and a runner that only works on one laptop is
    worse than no runner.
    """
    return subprocess.run(
        [sys.executable, str(path)],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=timeout,
    )


@pytest.fixture(scope="session", autouse=True)
def workshop_readout_template() -> None:
    """Build the pptx template if it isn't there.

    `Workshop Readout Template.pptx` is generated rather than committed -- it is
    a script so it stays reviewable and reproducible, and the corpus had no pptx
    at all before it. A fresh checkout therefore has no template and would skip
    the pptx suite for a file it can produce in a second.

    Building it needs the MOM, whose logo it lifts. If that's missing there is
    nothing to do: the pptx suite then skips on its own declared assets, which
    is the honest outcome.
    """
    if GENERATED_TEMPLATE.exists() or not (FILES_DIR / MOM).exists():
        return
    result = run_script(TEMPLATE_BUILDER, timeout=120)
    if result.returncode != 0:  # pragma: no cover - only on a broken corpus
        pytest.skip(
            f"could not build {GENERATED_TEMPLATE.name}:\n{result.stdout[-2000:]}",
            allow_module_level=True,
        )
